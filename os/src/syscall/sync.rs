use alloc::sync::Arc;
/// sleep syscall
pub fn sys_sleep(ms: usize) -> isize {
    trace!(
        "kernel:pid[{}] tid[{}] sys_sleep",
        current_task().unwrap().process.upgrade().unwrap().getpid(),
        current_task().unwrap().get_tid()
    );
    let expire_ms = get_time_ms() + ms;
    let task = current_task().unwrap();
    add_timer(expire_ms, task);
    block_current_and_run_next();
    0
}
/// mutex create syscall
pub fn sys_mutex_create(blocking: bool) -> isize {
    trace!(
        "kernel:pid[{}] tid[{}] sys_mutex_create",
        current_task().unwrap().process.upgrade().unwrap().getpid(),
        current_task().unwrap().get_tid()
    );
    let process = current_process();
    let mutex: Option<Arc<dyn Mutex>> = if !blocking {
        Some(Arc::new(MutexSpin::new()))
    } else {
        Some(Arc::new(MutexBlocking::new()))
    };
    let mut process_inner = process.inner_exclusive_access();
    if let Some(id) = process_inner
        .mutex_list
        .iter()
        .enumerate()
        .find(|(_, item)| item.is_none())
        .map(|(id, _)| id)
    {
        process_inner.mutex_list[id] = mutex;
        id as isize
    } else {
        process_inner.mutex_list.push(mutex);
        process_inner.update_mutex_info_while_creating();
        process_inner.mutex_list.len() as isize - 1
    }
}
/// mutex lock syscall
pub fn sys_mutex_lock(mutex_id: usize) -> isize {
    trace!(
        "kernel:pid[{}] tid[{}] sys_mutex_lock",
        current_task().unwrap().process.upgrade().unwrap().getpid(),
        current_task().unwrap().get_tid()
    );
    let process = current_process();
    let mut process_inner = process.inner_exclusive_access();
    // mutex not found
    if mutex_id >= process_inner.mutex_list.len() {
        return -1;
    }
    let mutex = Arc::clone(process_inner.mutex_list[mutex_id].as_ref().unwrap());
    if process_inner.get_enabled_deadlock_test() {
        let tid = current_task().unwrap().get_tid();
        // if the mutex is not allocated, alloc immediately
        if process_inner.mutex_available[mutex_id] {
            process_inner.mutex_available[mutex_id] = false;
            process_inner.mutex_allocation[tid][mutex_id] = true;
            drop(process_inner);
            drop(process);
            mutex.lock();
            return 0;
        }
        // if the mutex is allocated, run deadlock test
        process_inner.mutex_needed[tid][mutex_id] = true;
        if process_inner.no_mutex_deadlock(tid) {
            process_inner.waiting_list.push(current_task().unwrap());
            drop(process_inner);
            drop(process);
            if tid == 0 {
                suspend_current_and_run_next();
            } else {
                block_current_and_run_next();
            }
        } else {
            // Need to manually unlock and exit
            drop(process_inner);
            drop(process);
            return -0xDEAD;
        }
    } else {
        drop(process_inner);
        drop(process);
        mutex.lock();
    }
    0
}
/// mutex unlock syscall
pub fn sys_mutex_unlock(mutex_id: usize) -> isize {
    trace!(
        "kernel:pid[{}] tid[{}] sys_mutex_unlock",
        current_task().unwrap().process.upgrade().unwrap().getpid(),
        current_task().unwrap().get_tid()
    );
    let process = current_process();
    let mut process_inner = process.inner_exclusive_access();
    let mutex = Arc::clone(process_inner.mutex_list[mutex_id].as_ref().unwrap());
    let tid = current_task().unwrap().get_tid();
    process_inner.mutex_available[mutex_id] = true;
    process_inner.mutex_allocation[tid][mutex_id] = false;
    process_inner.mutex_needed[tid][mutex_id] = false;
    if process_inner.get_enabled_deadlock_test() && !process_inner.waiting_list.is_empty() {
        process_inner.wakeup_task_in_waiting_list();
    }
    drop(process_inner);
    drop(process);
    mutex.unlock();
    0
}
/// semaphore create syscall
pub fn sys_semaphore_create(res_count: usize) -> isize {
    trace!(
        "kernel:pid[{}] tid[{}] sys_semaphore_create",
        current_task().unwrap().process.upgrade().unwrap().getpid(),
        current_task().unwrap().get_tid()
    );
    let process = current_process();
    let mut process_inner = process.inner_exclusive_access();
    let id = if let Some(id) = process_inner
        .semaphore_list
        .iter()
        .enumerate()
        .find(|(_, item)| item.is_none())
        .map(|(id, _)| id)
    {
        process_inner.semaphore_list[id] = Some(Arc::new(Semaphore::new(res_count)));
        let allocated = process_inner.semaphore_available[id] - process_inner.semaphore_work[id];
        process_inner.semaphore_available[id] = res_count as isize;
        process_inner.semaphore_work[id] = res_count as isize - allocated;
        id
    } else {
        process_inner
            .semaphore_list
            .push(Some(Arc::new(Semaphore::new(res_count))));
        process_inner.update_semaphore_info_while_creating(res_count as isize);
        process_inner.semaphore_list.len() - 1
    };
    id as isize
}
